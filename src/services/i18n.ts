export function formatBHD(amount: number | undefined | null): string {
  if (amount === undefined || amount === null || isNaN(amount)) return '0.000 BHD';
  return `${amount.toFixed(3)} BHD`;
}

export function formatBHDLocalized(amount: number | undefined | null, lang: Language): string {
  if (amount === undefined || amount === null || isNaN(amount)) {
    return lang === 'ar' ? '0.000 د.ب' : '0.000 BHD';
  }
  return lang === 'ar' ? `${amount.toFixed(3)} د.ب` : `${amount.toFixed(3)} BHD`;
}
